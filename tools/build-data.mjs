// Bundle the deck metadata + words into a plain <script> file so the app works
// from file:// with no build step and no network.
//
//   node tools/build-data.mjs
//
// Source of words, in order of preference:
//   data/words.full.json   <- produced by tools/import-apkg.mjs (your own deck)
//   data/words.approx.json <- frequency-ranked approximation from tools/build-approx.mjs
//   data/words.seed.json   <- 20 public preview cards from tools/extract-public.mjs
//
// Dictionary HTML is kept out of the bundle (it is large); it is written to
// data/dict/<LEVEL>.json for lazy loading when the app runs on a local server.

import { readFileSync, writeFileSync, mkdirSync, existsSync, statSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => JSON.parse(readFileSync(join(ROOT, p), 'utf8'));
const pick = (...paths) => paths.find((p) => existsSync(join(ROOT, p)));

const deck = read('data/deck.json');
const wordsPath = pick('data/words.full.json', 'data/words.approx.json', 'data/words.seed.json');
if (!wordsPath) {
  console.error('No data/words.full.json, data/words.approx.json or data/words.seed.json found.');
  process.exit(1);
}

const words = read(wordsPath);
const source = wordsPath.includes('full') ? 'full' : wordsPath.includes('approx') ? 'approx' : 'seed';

const isBundled = (w) => {
  const core = {
    id: w.id, grade: w.grade, word: w.word, chn: w.chn, ipa: w.ipa,
    note: w.note || '', images: w.images || [], wordAudio: w.wordAudio || '',
    sentAudio: w.sentAudio || '', sentHtml: w.sentHtml || '',
  };
  return core;
};

const dictByLevel = {};
for (const w of words) {
  if (!w.dictionary) continue;
  (dictByLevel[w.grade] ||= []).push({ word: w.word, html: w.dictionary });
}

const bundle = {
  meta: {
    title: deck.title,
    cardId: deck.cardId,
    source,
    wordsPath,
    totalWords: words.length,
    builtAt: new Date().toISOString(),
    levelOrder: deck.levelOrder,
    levelCounts: deck.levelCounts,
    decks: deck.decks,
    model: { name: deck.model?.name, fields: deck.model?.fields },
  },
  words: words.map(isBundled),
};

mkdirSync(join(ROOT, 'assets/js'), { recursive: true });
mkdirSync(join(ROOT, 'data/dict'), { recursive: true });
for (const [level, entries] of Object.entries(dictByLevel)) {
  writeFileSync(join(ROOT, `data/dict/${level}.json`), JSON.stringify(entries), 'utf8');
}
writeFileSync(
  join(ROOT, 'assets/js/data.js'),
  `/* generated by tools/build-data.mjs - do not edit */\nwindow.RAZ_DATA = ${JSON.stringify(bundle)};\n`,
  'utf8',
);

const kb = (n) => (n / 1024).toFixed(0) + ' KB';
console.log(`source: ${source} (${words.length} words)`);
console.log(`levels: ${[...new Set(words.map((w) => w.grade))].join(', ')}`);
console.log(`assets/js/data.js: ${kb(statSync(join(ROOT, 'assets/js/data.js')).size)}`);
console.log(`dictionary levels: ${Object.keys(dictByLevel).join(', ') || '(none)'}`);
